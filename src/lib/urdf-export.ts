import JSZip from "jszip";
import { axisVector } from "@/lib/kinematics";
import type { AssemblyRecord } from "@/lib/types";

function sanitizeSlug(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .replace(/^_+|_+$/g, "") || "jointbench_asset"
  );
}

function fmt(n: number): string {
  return Number(n.toFixed(4)).toString();
}

export function generateUrdfXml(assembly: AssemblyRecord): string {
  const slug = sanitizeSlug(assembly.name);
  const { joint, parts, dimensions } = assembly;
  const movingParts = parts.filter((p) => p.role === "moving");
  const baseParts = parts.filter((p) => p.role === "base");

  const [ax, ay, az] = axisVector(joint.axis, joint.axisSign);
  const lower =
    joint.type === "revolute" ? (joint.minLimit * Math.PI) / 180 : joint.minLimit;
  const upper =
    joint.type === "revolute" ? (joint.maxLimit * Math.PI) / 180 : joint.maxLimit;

  const movingLabel = movingParts[0]?.label ?? "moving_link";
  const baseLabel = baseParts[0]?.label ?? "base_link";
  const [w, h, d] = dimensions;

  // Grasp handle offset relative to joint pivot frame
  const gx = joint.graspHandle[0] - joint.pivot[0];
  const gy = joint.graspHandle[1] - joint.pivot[1];
  const gz = joint.graspHandle[2] - joint.pivot[2];

  const baseMass = Number(Math.max(1.2, w * h * d * 42).toFixed(2));
  const movingMass = Number(Math.max(0.25, baseMass * 0.22).toFixed(2));

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by JointBench from Aholo Lux3D Part Split (${assembly.lineageLabel}) -->
<!-- Assembly: ${assembly.name} | Verdict: ${assembly.lastRun?.status.toUpperCase() ?? "UNCALIBRATED"} -->
<robot name="${slug}">
  <link name="${baseLabel}">
    <inertial>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <mass value="${baseMass}"/>
      <inertia ixx="${fmt((baseMass * (h * h + d * d)) / 12)}" ixy="0" ixz="0"
               iyy="${fmt((baseMass * (w * w + d * d)) / 12)}" iyz="0"
               izz="${fmt((baseMass * (w * w + h * h)) / 12)}"/>
    </inertial>
    <visual name="${baseLabel}_visual">
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry>
        <mesh filename="package://${slug}/meshes/${slug}_split.glb" scale="1 1 1"/>
      </geometry>
    </visual>
    <collision name="${baseLabel}_collision">
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry>
        <box size="${fmt(w)} ${fmt(h)} ${fmt(d)}"/>
      </geometry>
    </collision>
  </link>

  <link name="${movingLabel}">
    <inertial>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <mass value="${movingMass}"/>
      <inertia ixx="0.008" ixy="0" ixz="0" iyy="0.008" iyz="0" izz="0.008"/>
    </inertial>
    <visual name="${movingLabel}_visual">
      <origin xyz="${fmt(-joint.pivot[0])} ${fmt(-joint.pivot[1])} ${fmt(-joint.pivot[2])}" rpy="0 0 0"/>
      <geometry>
        <mesh filename="package://${slug}/meshes/${slug}_split.glb" scale="1 1 1"/>
      </geometry>
    </visual>
    <collision name="${movingLabel}_collision">
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry>
        <box size="${fmt(movingParts[0]?.size[0] ?? 0.25)} ${fmt(movingParts[0]?.size[1] ?? 0.2)} ${fmt(movingParts[0]?.size[2] ?? 0.05)}"/>
      </geometry>
    </collision>
  </link>

  <joint name="${slug}_articulated_joint" type="${joint.type}">
    <parent link="${baseLabel}"/>
    <child link="${movingLabel}"/>
    <origin xyz="${fmt(joint.pivot[0])} ${fmt(joint.pivot[1])} ${fmt(joint.pivot[2])}" rpy="0 0 0"/>
    <axis xyz="${ax} ${ay} ${az}"/>
    <limit lower="${fmt(lower)}" upper="${fmt(upper)}" effort="25.0" velocity="1.2"/>
    <dynamics damping="0.6" friction="0.15"/>
  </joint>

  <link name="grasp_handle_frame"/>

  <joint name="grasp_handle_fixed" type="fixed">
    <parent link="${movingLabel}"/>
    <child link="grasp_handle_frame"/>
    <origin xyz="${fmt(gx)} ${fmt(gy)} ${fmt(gz)}" rpy="0 0 0"/>
  </joint>
</robot>
`;
}

export function generateSimReadme(assembly: AssemblyRecord): string {
  const slug = sanitizeSlug(assembly.name);
  return `# ${assembly.name} (Sim-Ready URDF Package)

Generated by **JointBench** from **Aholo Lux3D** (${assembly.lineageLabel}).

## Contents
- \`${slug}.urdf\`: Calibrated ROS / MuJoCo / Isaac Sim URDF description with joint limits and \`grasp_handle_frame\`.
- \`meshes/${slug}_split.glb\`: Part-split 3D mesh containing ${assembly.parts.length} separable sub-meshes.
- \`grasp-spec.json\`: Machine-readable grasp handle coordinates, part-to-link bindings, and Lux3D provenance.
- \`test-report.json\`: Deterministic 24-waypoint 3-DOF robotic arm reachability and clearance report.

## Quick Load in Python (MuJoCo / PyBullet)
\`\`\`python
import pybullet as p
p.connect(p.GUI)
uid = p.loadURDF("${slug}.urdf", useFixedBase=True)
print("Loaded joints:", p.getNumJoints(uid))
\`\`\`
`;
}

export async function exportAssemblyUrdfZip(
  assembly: AssemblyRecord,
  resolveGlbBytes: (assembly: AssemblyRecord) => Promise<ArrayBuffer | null>
): Promise<{ filename: string; blob: Blob; urdfXml: string }> {
  const slug = sanitizeSlug(assembly.name);
  const zip = new JSZip();

  const urdfXml = generateUrdfXml(assembly);
  zip.file(`${slug}.urdf`, urdfXml);
  zip.file("README_SIM.md", generateSimReadme(assembly));

  zip.file(
    "grasp-spec.json",
    JSON.stringify(
      {
        schema: "jointbench.grasp-spec.v1",
        assemblyId: assembly.id,
        name: assembly.name,
        lineage: assembly.lineageLabel,
        lux3dMeta: assembly.lux3dMeta ?? null,
        dimensionsMeters: assembly.dimensions,
        joint: assembly.joint,
        partBindings: assembly.parts.map((p) => ({
          meshName: p.meshName,
          label: p.label,
          role: p.role,
          triangles: p.triangles,
        })),
      },
      null,
      2
    )
  );

  zip.file(
    "test-report.json",
    JSON.stringify(
      assembly.lastRun ?? {
        status: "uncalibrated",
        note: "Run 3-DOF Arm Test in JointBench before simulation deployment.",
      },
      null,
      2
    )
  );

  const glbBytes = await resolveGlbBytes(assembly);
  if (glbBytes) {
    zip.file(`meshes/${slug}_split.glb`, glbBytes);
  }

  const blob = await zip.generateAsync({ type: "blob" });
  return {
    filename: `${slug}-sim-ready-urdf.zip`,
    blob,
    urdfXml,
  };
}
